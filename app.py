data_preparada = pd.get_dummies(data_preparada, columns=['GENERO','RECIBIO_APOYO_FINANCIERO','RECIBIO_APOYO_ACADEMICO', 'RECIBIO_OTROS_APOYOS', 'COD_ESCUELA', 'ACADEMIC_STATUS_TERM'], drop_first=False, dtype=int)
