data_preparada[['TERM_ID','GPA_TERM', 'CREDITS_ATTEMPTED_TERM', 'CREDITS_FAILED_TERM', 'GPA_CUM', 'CREDITS_APPROVED_CUM_ALL', 'CREDITS_FAILED_CUM']]= min_max_scaler.transform(data_preparada[['TERM_ID','GPA_TERM', 'CREDITS_ATTEMPTED_TERM', 'CREDITS_FAILED_TERM', 'GPA_CUM', 'CREDITS_APPROVED_CUM_ALL', 'CREDITS_FAILED_CUM']])
