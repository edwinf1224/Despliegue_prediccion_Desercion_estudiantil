# Dataframe. Este Dataframe se crea para que en su interior quede la información que en el paso previo ha introducido el usuario
datos = [[TERM_ID, GPA_TERM, CREDITS_ATTEMPTED_TERM, CREDITS_FAILED_TERM, GPA_CUM, CREDITS_APPROVED_CUM_ALL, CREDITS_FAILED_CUM, COD_ESCUELA, ACADEMIC_STATUS_TERM, GENERO, RECIBIO_APOYO_FINANCIERO, RECIBIO_APOYO_ACADEMICO, RECIBIO_OTROS_APOYOS]]
